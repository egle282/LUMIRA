from pydantic import BaseModel, Field
from typing import List, Optional
from datetime import datetime

class PanchangaSummary(BaseModel):
    tithi: str
    vara: str
    nakshatra: str
    yoga: str
    karana: str
    auspiciousness_score: int = Field(..., ge=0, le=10)

class TransitSummary(BaseModel):
    planet: str
    current_sign: str
    house_transiting: int
    impact: str = Field(..., description="E.g., positive, negative, neutral")

class DailyBriefing(BaseModel):
    date: datetime
    user_id: str
    panchanga: PanchangaSummary
    key_transits: List[TransitSummary]
    focus_life_areas: List[str] = Field(..., description="Which life areas are activated today")
    ai_interpretation: str = Field(..., description="Personalized daily briefing generated by AI")
    recommendations: List[str]
    cautions: List[str]
    is_mock: bool = False

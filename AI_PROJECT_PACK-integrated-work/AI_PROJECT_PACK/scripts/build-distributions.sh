#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/dist"
rm -rf "$OUT"
mkdir -p "$OUT/npm/bundle" "$OUT/pip/src/ai_project_pack/bundle"
"$ROOT/scripts/update-source-hashes.sh"
cp -R "$ROOT/install.sh" "$ROOT/platform-manifest.json" "$ROOT/source-hashes.tsv" "$ROOT/adapters" "$ROOT/source" "$ROOT/README.md" "$ROOT/source/PACK_MANIFEST.md" "$OUT/npm/bundle/"
cp -R "$OUT/npm/bundle/." "$OUT/pip/src/ai_project_pack/bundle/"
cp -R "$ROOT/packaging/npm/." "$OUT/npm/"
cp -R "$ROOT/packaging/pip/." "$OUT/pip/"
rm -rf "$OUT/npm/bundle/packaging" "$OUT/pip/src/ai_project_pack/bundle/packaging"
printf 'Distribution staging created at %s\n' "$OUT"
printf 'npm: cd %s/npm && npm pack\n' "$OUT"
printf 'pip: cd %s/pip && python -m build\n' "$OUT"
